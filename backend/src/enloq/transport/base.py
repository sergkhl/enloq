from pathlib import Path
from typing import Protocol

from ..domain.catalog import (
    CatalogLibrary,
    CatalogPackData,
    CatalogSearchData,
    NativeCatalogSource,
    NativePackReference,
)
from ..domain.deletion import (
    DeleteDescription,
    DeleteEvidence,
    DeleteReceipt,
    DeletionRead,
)
from ..domain.delivery import ReceiptBatch, ReceiptSink, SendDescription, SendEvidence
from ..domain.models import Message, Reaction, ReactionSnapshot


class TelegramTransport(Protocol):
    account_id: int
    connected: bool

    async def catalog_entitlement(self) -> bool: ...
    async def catalog_library(self) -> CatalogLibrary: ...
    async def catalog_pack(self, pack: NativePackReference) -> CatalogPackData: ...
    async def catalog_search(
        self, query: str, offset: str = ""
    ) -> CatalogSearchData: ...
    async def catalog_refresh_document(
        self, source: NativeCatalogSource
    ) -> NativeCatalogSource: ...
    async def catalog_download(
        self,
        source: NativeCatalogSource,
        path: Path,
        *,
        max_bytes: int,
        thumb: bool = False,
    ) -> NativeCatalogSource: ...

    def bind_receipts(self, sink: ReceiptSink) -> None: ...
    async def review_group_send(self, description: SendDescription, guard): ...
    async def send(
        self, description: SendDescription, evidence: SendEvidence
    ) -> ReceiptBatch: ...
    async def delete(
        self, description: DeleteDescription, evidence: DeleteEvidence
    ) -> DeleteReceipt: ...
    async def inspect_deletion(
        self, peer: str, identities: list[int] | tuple[int, ...]
    ) -> DeletionRead: ...
    def held_until(self, description: SendDescription) -> float: ...
    async def refresh_delivery(self) -> None: ...
    async def exact(self, peer: str, identity: int) -> Message | None: ...
    async def exact_many(self, peer: str, identities: list[int]) -> list[Message]: ...
    async def history(self, peer: str, before: int, limit: int) -> list[Message]: ...
    async def read(self, peer: str, through: int) -> None: ...
    async def typing(self, peer: str) -> None: ...
    async def reaction_options(self) -> dict: ...
    async def profile(self, peer: str) -> dict: ...
    async def send_reaction(
        self, peer: str, identity: int, reactions: list[Reaction]
    ) -> ReactionSnapshot | None: ...
    async def unread_reactions(
        self, peer: str
    ) -> list[tuple[int, ReactionSnapshot]]: ...
    async def close(self) -> None: ...
